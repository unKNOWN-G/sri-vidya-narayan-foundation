"""Isolated build checks for canonical reader data and cache versions."""
import contextlib
import hashlib
import importlib.util
import io
import json
from pathlib import Path
import sys
import tempfile
import unittest
from unittest.mock import patch

SCRIPTS = Path(__file__).resolve().parents[1] / "scripts"
sys.path.insert(0, str(SCRIPTS))
SPEC = importlib.util.spec_from_file_location("reader_build", SCRIPTS / "build.py")
MODULE = importlib.util.module_from_spec(SPEC)
SPEC.loader.exec_module(MODULE)


class ReaderBuildTest(unittest.TestCase):
    def setUp(self):
        temporary = tempfile.TemporaryDirectory()
        self.addCleanup(temporary.cleanup)
        self.root = Path(temporary.name).resolve()
        self.cards = [{"id": "message", "type": "folded", "sheets": {"outside": "assets/outside.webp", "inside": "assets/inside.webp"}, "pages": [{"body": "Words supplied with the card."}]}]
        self.pearls = [{"number": 1, "text": "A supplied teaching.", "source_side": "right"}]
        self.write("content/site.json", {"categories": [], "events": []})
        self.write("content/collections/cards.json", self.cards)
        self.write("content/collections/pearls.json", {"entries": self.pearls})
        for filename in ("event-cards-data.js", "pearls-data.js"):
            self.write("src/" + filename, "// Generated by the build.\n")
        self.write("src/experience.css", "body { color: green; }\n")
        self.write("src/message-spotlight.js", "window.loaded = true;\n")
        self.write("src/index.html", '<link href="experience.css"><script src="message-spotlight.js?mode=full#reader"></script><script src="event-cards-data.js"></script>')
        self.write("src/nested/reader.html", '<script src="../pearls-data.js"></script>')

    def write(self, relative, data):
        path = self.root / relative
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(data if isinstance(data, str) else json.dumps(data))

    def build(self):
        with patch.object(MODULE, "ROOT", self.root), contextlib.redirect_stdout(io.StringIO()):
            return MODULE.build(skip_validation=True)

    def generated(self, output, name):
        text = (output / name).read_text()
        return json.loads(text.split(" = ", 1)[1].rstrip().removesuffix(";"))

    def test_home_totals_keep_causes_and_approximation_distinct(self):
        self.write("content/site.json", {"categories": [{"id": "education", "homeContributionCategory": "education"}, {"id": "annadanam", "homeContributionCategory": "annadanam"}], "collections": {"contributions": "content/collections/contributions.json"}})
        self.write("content/collections/contributions.json", {"records": [{"id": "school", "category": "education", "amount": 200000}, {"id": "reported", "category": "education", "amount": 100000, "approximate": True}, {"id": "food", "category": "annadanam", "amount": 50000}]})
        output = self.build()
        categories = json.loads((output / "content/site.json").read_text())["categories"]
        self.assertEqual(categories[0]["homeContributionTotal"], {"amount": 300000, "approximate": True})
        self.assertEqual(categories[1]["homeContributionTotal"], {"amount": 50000, "approximate": False})

    def test_duplicate_contributions_cannot_inflate_home_total(self):
        self.write("content/site.json", {"categories": [{"id": "education", "homeContributionCategory": "education"}], "collections": {"contributions": "content/collections/contributions.json"}})
        self.write("content/collections/contributions.json", {"records": [{"id": "same", "category": "education", "amount": 10}, {"id": "same", "category": "education", "amount": 10}]})
        with self.assertRaisesRegex(ValueError, "Duplicate contribution IDs"):
            self.build()

    def test_generates_exact_presentation_and_pearls_without_changing_sources(self):
        output = self.build()
        self.assertEqual(self.generated(output, "event-cards-data.js"), self.cards)
        self.assertEqual(self.generated(output, "pearls-data.js"), self.pearls)
        self.assertEqual(json.loads((self.root / "content/collections/cards.json").read_text()), self.cards)
        self.assertEqual((self.root / "src/event-cards-data.js").read_text(), "// Generated by the build.\n")

    def test_versions_all_local_styles_and_scripts_including_nested_pages(self):
        output = self.build()
        html = (output / "index.html").read_text()
        for name in ("experience.css", "event-cards-data.js"):
            digest = hashlib.sha256((output / name).read_bytes()).hexdigest()[:12]
            self.assertIn(f'{name}?v={digest}', html)
        self.assertIn("message-spotlight.js?mode=full&v=", html)
        self.assertIn("#reader", html)
        self.assertIn("../pearls-data.js?v=", (output / "nested/reader.html").read_text())

    def test_canonical_edit_changes_bundle_and_its_html_version(self):
        output = self.build()
        before = (output / "index.html").read_text()
        self.cards[0]["pages"][0]["body"] = "A reviewed revision."
        self.write("content/collections/cards.json", self.cards)
        self.build()
        self.assertEqual(self.generated(output, "event-cards-data.js"), self.cards)
        self.assertNotEqual(before, (output / "index.html").read_text())

    def test_missing_canonical_content_fails_instead_of_shipping_stub(self):
        (self.root / "content/collections/cards.json").unlink()
        with self.assertRaisesRegex(ValueError, "Missing canonical reader content: cards.json"):
            self.build()


    def test_share_previews_escape_text_and_preserve_route(self):
        self.write("content/site.json", {"categories": [{"id": "care", "title": 'Care <and> "kindness"', "caption": 'Read & reflect.'}], "events": []})
        self.write("content/image-variants.json", {"assets/photo.webp": {"width": 800, "height": 600, "sources": [{"src": "assets/small.webp", "width": 400}]}})
        output = self.build()
        manifest = json.loads((output / "content/site.json").read_text())
        relative = manifest["sharePages"]["#/category/care"]
        html = (output / relative).read_text()
        self.assertIn('Care &lt;and&gt; &quot;kindness&quot;', html)
        self.assertIn('../../index.html#/category/care', html)
        self.assertIn('property="og:image"', html)
        self.assertEqual(manifest["imageVariants"]["assets/photo.webp"]["height"], 600)

    def test_share_previews_reject_path_traversal(self):
        self.write("content/site.json", {"categories": [{"id": "../../outside", "title": "Invalid"}], "events": []})
        with self.assertRaisesRegex(ValueError, "Invalid share page identifier"):
            self.build()

if __name__ == "__main__":
    unittest.main()
